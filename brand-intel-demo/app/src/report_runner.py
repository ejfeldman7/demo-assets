def run_schedule(schedule_id: str, workspace_client=None) -> dict:
    """Execute a scheduled report or alert by schedule_id.

    Reads config from Lakebase, runs the Supervisor Agent, and handles
    email delivery + PDF storage.

    Returns dict with: status, report, alert_breached, run_id, email_sent.
    """
    from supervisor import SupervisorAgent
    from db import execute_query, execute_insert

    # 1. Read schedule config
    schedule_df = execute_query(
        """
        SELECT schedule_id, schedule_type, report_name, report_question,
               alert_template, alert_threshold, alert_scope_json,
               alert_cooldown_days, last_alert_sent_at,
               recipients, created_by, genie_space_ids
        FROM bi_report_schedules
        WHERE schedule_id = %s AND is_active = TRUE
        """,
        (schedule_id,),
    )

    if schedule_df.empty:
        return {"status": "error", "error": "Schedule not found or inactive"}

    config = schedule_df.iloc[0]
    schedule_type = config.get("schedule_type", "report")
    report_name = config.get("report_name", "Untitled")
    question = config.get("report_question", "")
    recipients = config.get("recipients", [])
    created_by = config.get("created_by", "unknown@example.com")
    run_id = str(uuid.uuid4())

    if isinstance(recipients, str):
        recipients = [r.strip() for r in recipients.split(",") if r.strip()]
    if not recipients:
        recipients = [created_by]

    # 2. For alerts: check cooldown
    if schedule_type == "alert":
        cooldown_days = config.get("alert_cooldown_days") or 1
        last_sent = config.get("last_alert_sent_at")
        if last_sent:
            from datetime import timedelta
            if datetime.utcnow() - last_sent < timedelta(days=cooldown_days):
                logger.info("Alert %s is in cooldown — skipping", schedule_id)
                execute_insert(
                    """
                    INSERT INTO bi_report_audit_log
                        (run_id, schedule_id, run_started_at, run_completed_at, status,
                         alert_breached)
                    VALUES (%s, %s, now(), now(), 'cooldown', FALSE)
                    """,
                    (run_id, schedule_id),
                )
                return {"status": "cooldown", "run_id": run_id}

    # 3. Run Supervisor Agent — resolve genie spaces for this schedule
    from db import get_genies_by_ids, get_active_genies as _get_active_genies
    genie_space_ids = config.get("genie_space_ids")
    if genie_space_ids:
        genies_df = get_genies_by_ids(genie_space_ids)
    else:
        genies_df = _get_active_genies()
    genies = genies_df.to_dict("records")
    agent = SupervisorAgent(workspace_client=workspace_client, genies=genies)
    try:
        result = agent.run(
            question=question,
            user_email=created_by,
        )
    except Exception as e:
        logger.error("Agent run failed for schedule %s: %s", schedule_id, e)
        execute_insert(
            """
            INSERT INTO bi_report_audit_log
                (run_id, schedule_id, run_started_at, run_completed_at, status, error_message)
            VALUES (%s, %s, now(), now(), 'failed', %s)
            """,
            (run_id, schedule_id, str(e)),
        )
        return {"status": "error", "error": str(e), "run_id": run_id}

    report_md = result.get("report", "")
    plan = result.get("plan", [])

    # 4. For alerts: evaluate if there's an issue
    alert_breached = False
    alert_eval = {}
    if schedule_type == "alert":
        threshold_context = ""
        alert_threshold = config.get("alert_threshold")
        alert_template = config.get("alert_template")
        if alert_threshold is not None:
            threshold_context = f"Alert template: {alert_template}, Threshold: {alert_threshold}"
        scope = config.get("alert_scope_json")
        if scope:
            if isinstance(scope, str):
                try:
                    scope = json.loads(scope)
                except Exception:
                    pass
            if isinstance(scope, dict):
                threshold_context += f", Scope: {json.dumps(scope)}"

        alert_eval = agent.evaluate_alert(report_md, question, threshold_context)
        alert_breached = alert_eval.get("breached", False)

        if not alert_breached:
            # No issue — log and exit without email
            execute_insert(
                """
                INSERT INTO bi_report_audit_log
                    (run_id, schedule_id, run_started_at, run_completed_at, status,
                     agent_plan_json, alert_breached)
                VALUES (%s, %s, now(), now(), 'no_breach', %s, FALSE)
                """,
                (run_id, schedule_id, json.dumps(plan)),
            )
            return {
                "status": "no_breach",
                "report": report_md,
                "alert_breached": False,
                "alert_summary": alert_eval.get("summary", ""),
                "run_id": run_id,
            }

    # 5. Generate HTML + PDF
    is_alert = schedule_type == "alert"
    title = f"{'ALERT: ' if is_alert else ''}{report_name}"

    # For alerts, prepend the alert summary to the report
    if is_alert and alert_eval:
        severity = alert_eval.get("severity", "medium").upper()
        summary = alert_eval.get("summary", "")
        report_md = f"**Alert Severity: {severity}**\n\n{summary}\n\n---\n\n{report_md}"

    html_report = markdown_to_html(report_md, title=title, is_alert=is_alert)
    pdf_bytes = html_to_pdf(html_report, report_md=report_md, title=title)

    # 6. Save PDF to UC Volume
    volume_path = None
    pdf_filename = make_pdf_filename(report_name)
    if pdf_bytes:
        volume_path = save_to_volume(
            pdf_bytes, report_name,
            workspace_client=workspace_client,
        )

    # 7. Send email
    date_str = datetime.utcnow().strftime("%Y-%m-%d")
    if is_alert:
        subject = f"[ALERT] {report_name} -- Threshold Breached {date_str}"
    else:
        subject = f"[Report] {report_name} -- {date_str}"

    email_sent = send_email(
        recipients=recipients,
        subject=subject,
        html_body=html_report,
        pdf_bytes=pdf_bytes,
        pdf_filename=pdf_filename,
    )

    # 8. Write audit log
    breach_value = alert_eval.get("key_metric_value") if alert_eval else None
    execute_insert(
        """
        INSERT INTO bi_report_audit_log
            (run_id, schedule_id, run_started_at, run_completed_at, status,
             agent_plan_json, alert_breached, alert_breach_value,
             report_volume_path, email_sent_to, email_sent_at)
        VALUES (%s, %s, now(), now(), %s, %s, %s, %s, %s, %s, %s)
        """,
        (
            run_id,
            schedule_id,
            "success",
            json.dumps(plan),
            alert_breached if is_alert else None,
            float(breach_value) if breach_value is not None else None,
            volume_path,
            recipients if email_sent else None,
            datetime.utcnow() if email_sent else None,
        ),
    )

    # 9. For alerts: update last_alert_sent_at
    if is_alert and alert_breached and email_sent:
        execute_insert(
            "UPDATE bi_report_schedules SET last_alert_sent_at = now() WHERE schedule_id = %s",
            (schedule_id,),
        )

    return {
        "status": "success",
        "report": report_md,
        "html": html_report,
        "pdf_bytes": pdf_bytes,
        "alert_breached": alert_breached,
        "alert_eval": alert_eval,
        "email_sent": email_sent,
        "volume_path": volume_path,
        "run_id": run_id,
    }


