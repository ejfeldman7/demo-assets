def save_to_volume(
    pdf_bytes: bytes,
    title: str,
    workspace_client=None,
) -> Optional[str]:
    """Save PDF to UC Volume. Returns the volume path or None."""
    try:
        if workspace_client is None:
            from databricks.sdk import WorkspaceClient
            workspace_client = WorkspaceClient()

        filename = make_pdf_filename(title)
        volume_path = f"/Volumes/brand_intel_demo/assets/reports/{filename}"

        workspace_client.files.upload(
            volume_path,
            io.BytesIO(pdf_bytes),
            overwrite=True,
        )
        logger.info("PDF saved to %s", volume_path)
        return volume_path
    except Exception as e:
        logger.error("Failed to save PDF to UC Volume: %s", e)
        return None


