# Brand accent color
_AD_RED = (204, 0, 0)
_DARK = (30, 30, 30)
_GRAY = (100, 100, 100)
_LIGHT_BG = (245, 245, 245)
_HIGHLIGHT_BG = (255, 243, 205)


def _init_pdf_fonts(pdf):
    """Register DejaVu Unicode fonts bundled in app/fonts/."""
    from pathlib import Path
    font_dir = Path(__file__).parent / "fonts"
    pdf.add_font("DejaVu", "", str(font_dir / "DejaVuSans.ttf"))
    pdf.add_font("DejaVu", "B", str(font_dir / "DejaVuSans-Bold.ttf"))
    pdf.add_font("DejaVu", "I", str(font_dir / "DejaVuSans-Oblique.ttf"))
    pdf.add_font("DejaVu", "BI", str(font_dir / "DejaVuSans-BoldOblique.ttf"))


def _render_inline(pdf, text: str, default_style: str = ""):
    """Render a line of text with **bold** and *italic* inline spans."""
    import re
    # Split on bold and italic markers
    parts = re.split(r'(\*\*.*?\*\*|\*.*?\*)', text)
    for part in parts:
        if part.startswith("**") and part.endswith("**"):
            pdf.set_font("DejaVu", "B", pdf.font_size_pt)
            pdf.write(5, part[2:-2])
            pdf.set_font("DejaVu", default_style, pdf.font_size_pt)
        elif part.startswith("*") and part.endswith("*"):
            pdf.set_font("DejaVu", "I", pdf.font_size_pt)
            pdf.write(5, part[1:-1])
            pdf.set_font("DejaVu", default_style, pdf.font_size_pt)
        else:
            pdf.write(5, part)


def _render_text_segment(pdf, text: str, left_margin: float):
    """Render a block of markdown text (no Vega-Lite) into the PDF."""
    lines = text.split("\n")
    in_list = False
    numbered_idx = 0

    for line in lines:
        stripped = line.strip()

        if not stripped:
            if in_list:
                in_list = False
                numbered_idx = 0
            pdf.ln(3)
            continue

        # H1
        if stripped.startswith("# ") and not stripped.startswith("##"):
            pdf.ln(4)
            pdf.set_font("DejaVu", "B", 18)
            pdf.set_text_color(*_AD_RED)
            pdf.cell(0, 10, stripped[2:], new_x="LMARGIN", new_y="NEXT")
            pdf.set_draw_color(*_AD_RED)
            pdf.line(left_margin, pdf.get_y(), 190, pdf.get_y())
            pdf.ln(3)
            pdf.set_text_color(*_DARK)
            continue

        # H2
        if stripped.startswith("## ") and not stripped.startswith("###"):
            pdf.ln(6)
            pdf.set_font("DejaVu", "B", 14)
            pdf.set_text_color(*_AD_RED)
            pdf.cell(0, 8, stripped[3:], new_x="LMARGIN", new_y="NEXT")
            pdf.set_draw_color(200, 200, 200)
            pdf.line(left_margin, pdf.get_y() + 1, 190, pdf.get_y() + 1)
            pdf.ln(4)
            pdf.set_text_color(*_DARK)
            continue

        # H3
        if stripped.startswith("### "):
            pdf.ln(4)
            pdf.set_font("DejaVu", "B", 12)
            pdf.set_text_color(60, 60, 60)
            pdf.cell(0, 7, stripped[4:], new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)
            pdf.set_text_color(*_DARK)
            continue

        # Horizontal rule
        if stripped in ("---", "***", "___"):
            pdf.ln(3)
            pdf.set_draw_color(200, 200, 200)
            pdf.line(left_margin, pdf.get_y(), 190, pdf.get_y())
            pdf.ln(3)
            continue

        # Bullet list
        if stripped.startswith("- ") or stripped.startswith("* ") or stripped.startswith("\u2022 "):
            in_list = True
            bullet_text = stripped.lstrip("-*\u2022 ").strip()
            pdf.set_font("DejaVu", "", 10)
            pdf.cell(6, 5, "\u2022")
            _render_inline(pdf, bullet_text)
            pdf.ln(6)
            continue

        # Numbered list
        if len(stripped) > 2 and stripped[0].isdigit() and stripped[1] in (".", ")"):
            in_list = True
            numbered_idx += 1
            item_text = stripped[2:].strip().lstrip(". )")
            pdf.set_font("DejaVu", "B", 10)
            pdf.cell(8, 5, f"{numbered_idx}.")
            pdf.set_font("DejaVu", "", 10)
            _render_inline(pdf, item_text)
            pdf.ln(6)
            continue

        if len(stripped) > 3 and stripped[:2].isdigit() and stripped[2] in (".", ")"):
            in_list = True
            numbered_idx += 1
            item_text = stripped[3:].strip().lstrip(". )")
            pdf.set_font("DejaVu", "B", 10)
            pdf.cell(8, 5, f"{numbered_idx}.")
            pdf.set_font("DejaVu", "", 10)
            _render_inline(pdf, item_text)
            pdf.ln(6)
            continue

        # Regular paragraph text
        pdf.set_font("DejaVu", "", 10)
        _render_inline(pdf, stripped)
        pdf.ln(5)


def html_to_pdf(html_content: str, report_md: str = "", title: str = "") -> Optional[bytes]:
    """Build a branded PDF directly from markdown for clean formatting.

    Falls back to the HTML content if report_md is not provided.
    """
    try:
        from fpdf import FPDF

        pdf = FPDF(orientation="P", unit="mm", format="A4")
        pdf.set_auto_page_break(auto=True, margin=25)
        _init_pdf_fonts(pdf)

        # -- Title page header --
        pdf.add_page()
        left_margin = 20
        pdf.set_left_margin(left_margin)
        pdf.set_right_margin(20)

        # Red header bar
        pdf.set_fill_color(*_AD_RED)
        pdf.rect(0, 0, 210, 28, "F")
        pdf.set_font("DejaVu", "B", 18)
        pdf.set_text_color(255, 255, 255)
        pdf.set_xy(left_margin, 6)
        display_title = title
        # Extract title from HTML if not provided
        if not display_title and "<h1>" in html_content:
            display_title = html_content.split("<h1>")[1].split("</h1>")[0]
        if not display_title:
            display_title = "Report"
        pdf.cell(0, 10, display_title, new_x="LMARGIN", new_y="NEXT")

        # Subtitle line
        pdf.set_font("DejaVu", "I", 9)
        pdf.set_text_color(220, 220, 220)
        timestamp = datetime.utcnow().strftime("%B %d, %Y at %H:%M UTC")
        pdf.cell(0, 5, f"Generated {timestamp}", new_x="LMARGIN", new_y="NEXT")

        pdf.set_text_color(*_DARK)
        pdf.ln(12)

        # -- Parse markdown if available, otherwise fall back to HTML body text --
        if not report_md:
            # Extract text from HTML as fallback
            import re
            text = html_content
            if "<body>" in text:
                text = text.split("<body>", 1)[1].rsplit("</body>", 1)[0]
            text = re.sub(r'<[^>]+>', '', text)
            pdf.set_font("DejaVu", "", 10)
            pdf.multi_cell(0, 5, text)
            return bytes(pdf.output())

        # -- Pre-render Vega-Lite charts and strip them from markdown --
        _spec_to_png = None
        try:
            from viz_utils import split_markdown_and_charts, spec_to_png as _s2p
            segments = split_markdown_and_charts(report_md)
            _spec_to_png = _s2p
        except ImportError:
            segments = [{"type": "text", "content": report_md}]

        # Render each segment: text segments go through the line-by-line
        # renderer, chart segments get rendered as PNG images.
        for segment in segments:
            if segment["type"] == "vega-lite":
                png = _spec_to_png(segment["spec"]) if _spec_to_png else None
                if png:
                    try:
                        pdf.ln(4)
                        img_data = io.BytesIO(png)
                        pdf.image(img_data, x=left_margin, w=170)
                        pdf.ln(4)
                    except Exception as img_err:
                        logger.warning("Failed to embed chart image in PDF: %s", img_err)
                continue

            # -- Render text segment line by line --
            _render_text_segment(pdf, segment["content"], left_margin)

        # -- Footer --
        pdf.ln(10)
        pdf.set_draw_color(200, 200, 200)
        pdf.line(left_margin, pdf.get_y(), 190, pdf.get_y())
        pdf.ln(3)
        pdf.set_font("DejaVu", "I", 8)
        pdf.set_text_color(*_GRAY)
        pdf.cell(0, 4, f"Generated by Brand Manager Forecasting Intelligence on {timestamp}",
                 new_x="LMARGIN", new_y="NEXT")
        if APP_URL:
            pdf.set_text_color(0, 102, 204)
            pdf.cell(0, 4, "Open in App", link=APP_URL)

        return bytes(pdf.output())
    except ImportError:
        logger.warning("fpdf2 not installed -- PDF generation skipped.")
        return None
    except Exception as e:
        logger.error("PDF generation failed: %s", e)
        return None


