def markdown_to_html(report_md: str, title: str = "Report", is_alert: bool = False) -> str:
    """Convert a markdown report to a styled HTML document.

    Vega-Lite specs are rendered to PNG and embedded as base64 <img> tags.
    """
    import base64

    # Split out charts, render to PNG, and build HTML segments
    chart_html_parts = []
    try:
        from viz_utils import split_markdown_and_charts, spec_to_png
        segments = split_markdown_and_charts(report_md)
        for seg in segments:
            if seg["type"] == "vega-lite":
                png = spec_to_png(seg["spec"])
                if png:
                    b64 = base64.b64encode(png).decode("ascii")
                    chart_html_parts.append(
                        f'<div style="text-align:center;margin:16px 0;">'
                        f'<img src="data:image/png;base64,{b64}" '
                        f'style="max-width:100%;border:1px solid #e0e0e0;border-radius:4px;" />'
                        f'</div>'
                    )
                # else: skip failed chart silently
            else:
                chart_html_parts.append(
                    markdown.markdown(seg["content"], extensions=["tables", "fenced_code"])
                )
    except ImportError:
        chart_html_parts.append(
            markdown.markdown(report_md, extensions=["tables", "fenced_code"])
        )

    html_body = "\n".join(chart_html_parts)

    banner = ""
    if is_alert:
        banner = '<div class="alert-banner"><strong>ALERT TRIGGERED</strong> — This alert fired because the Supervisor Agent identified an actionable issue.</div>'

    timestamp = datetime.utcnow().strftime("%B %d, %Y at %H:%M UTC")
    app_link = f'<a href="{APP_URL}">Open in App</a>' if APP_URL else ""

    return f"""<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>{title}</title><style>{REPORT_CSS}</style></head>
<body>
<h1>{title}</h1>
{banner}
{html_body}
<div class="footer">
    Generated by Brand Manager Forecasting Intelligence on {timestamp}. {app_link}
</div>
</body>
</html>"""


