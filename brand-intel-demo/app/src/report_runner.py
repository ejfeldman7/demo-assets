def make_pdf_filename(title: str, timestamp: Optional[datetime] = None) -> str:
    """Generate a snake_case PDF filename from a report title + timestamp.

    e.g. "Weekly Accuracy Report" -> "weekly_accuracy_report_20260307_0454.pdf"
    """
    import re
    ts = timestamp or datetime.utcnow()
    # Lowercase, replace non-alphanumeric with underscore, collapse multiple underscores
    slug = re.sub(r'[^a-z0-9]+', '_', title.lower()).strip('_')
    return f"{slug}_{ts.strftime('%Y%m%d_%H%M')}.pdf"


