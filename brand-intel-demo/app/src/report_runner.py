def generate_proactive_report(
    findings: list[dict],
    memory_update: dict,
    schedule_name: str = "Proactive Analysis",
) -> dict:
    """Generate HTML + PDF from proactive agent findings.

    Adapts the structured findings format from proactive_agent.py into the
    same report format used by run_schedule().

    Returns dict with: report_md, html, pdf_bytes, title.
    """
    # Build markdown report from findings
    parts = []
    parts.append(f"## Executive Summary\n")

    narrative = memory_update.get("narrative", "")
    if narrative:
        parts.append(narrative)
    parts.append("")

    if findings:
        parts.append(f"## Findings ({len(findings)} issues detected)\n")
        for i, f in enumerate(findings, 1):
            severity = f.get("severity", "notable").upper()
            sku = f.get("sku", "Unknown")
            ftype = f.get("type", "anomaly").replace("_", " ").title()
            desc = f.get("description", "")
            action = f.get("recommended_action", "")

            parts.append(f"### {i}. [{severity}] {ftype} — {sku}\n")
            if desc:
                parts.append(desc)
            if action:
                parts.append(f"\n**Recommended Action:** {action}")
            parts.append("")
    else:
        parts.append("## No Actionable Findings\n")
        parts.append("All monitored metrics are within normal ranges. No anomalies detected.")

    # Add watching list
    watching = memory_update.get("watching", [])
    if watching:
        parts.append("## Active Watch List\n")
        for w in watching:
            topic = w.get("topic", "")
            sev = w.get("severity", "")
            trend = w.get("trend", "")
            parts.append(f"- **{topic}** — {sev}, {trend}")
        parts.append("")

    # Add analysis details if present
    analysis = memory_update.get("analysis_text", "")
    if analysis and len(analysis) > 100:
        parts.append("## Detailed Analysis\n")
        # Strip the JSON memory update block from the analysis text
        import re
        cleaned = re.sub(r'```json\s*\{.*?\}\s*```', '', analysis, flags=re.DOTALL).strip()
        if cleaned:
            parts.append(cleaned)

    report_md = "\n".join(parts)
    title = f"Proactive Analysis — {schedule_name}"

    html_report = markdown_to_html(report_md, title=title)
    pdf_bytes = html_to_pdf(html_report, report_md=report_md, title=title)

    return {
        "report_md": report_md,
        "html": html_report,
        "pdf_bytes": pdf_bytes,
        "title": title,
    }


def run_proactive_schedule(schedule_id: str, workspace_client=None) -> dict:
    """Execute a proactive analysis schedule.

    Runs the proactive agent, generates the report, sends email, logs audit.
    """
    from proactive_agent import run_proactive_agent
    from db import execute_query, execute_insert

    # Read schedule config
    schedule_df = execute_query(
        """
        SELECT schedule_id, report_name, recipients, created_by, genie_space_ids
        FROM bi_report_schedules
        WHERE schedule_id = %s AND is_active = TRUE
        """,
        (schedule_id,),
    )
    if schedule_df.empty:
        return {"status": "error", "error": "Schedule not found or inactive"}

    config = schedule_df.iloc[0]
    report_name = config.get("report_name", "Proactive Analysis")
    recipients = config.get("recipients", [])
    created_by = config.get("created_by", "unknown@example.com")
    run_id = str(uuid.uuid4())

    if isinstance(recipients, str):
        recipients = [r.strip() for r in recipients.split(",") if r.strip()]
    if not recipients:
        recipients = [created_by]

    # Resolve genie spaces for this schedule
    from db import get_genies_by_ids, get_active_genies as _get_active_genies
    genie_space_ids = config.get("genie_space_ids")
    if genie_space_ids:
        genies_df = get_genies_by_ids(genie_space_ids)
    else:
        genies_df = _get_active_genies()
    genies = genies_df.to_dict("records")

    # Run proactive agent
    try:
        findings, memory_update = run_proactive_agent(
            schedule_id=schedule_id,
            run_id=run_id,
            workspace_client=workspace_client,
            genies=genies,
        )
    except Exception as e:
        logger.error("Proactive agent failed for schedule %s: %s", schedule_id, e)
        execute_insert(
            """
            INSERT INTO bi_report_audit_log
                (run_id, schedule_id, run_started_at, run_completed_at, status, error_message)
            VALUES (%s, %s, now(), now(), 'failed', %s)
            """,
            (run_id, schedule_id, str(e)),
        )
        return {"status": "error", "error": str(e), "run_id": run_id}

    # Generate report
    report = generate_proactive_report(findings, memory_update, schedule_name=report_name)

    # Save PDF
    volume_path = None
    if report.get("pdf_bytes"):
        volume_path = save_to_volume(
            report["pdf_bytes"], report_name,
            workspace_client=workspace_client,
        )

    # Send email
    date_str = datetime.utcnow().strftime("%Y-%m-%d")
    finding_count = len(findings)
    subject = f"[Proactive] {report_name} — {finding_count} findings — {date_str}"

    email_sent = send_email(
        recipients=recipients,
        subject=subject,
        html_body=report["html"],
        pdf_bytes=report.get("pdf_bytes"),
        pdf_filename=make_pdf_filename(report_name),
    )

    # Audit log
    execute_insert(
        """
        INSERT INTO bi_report_audit_log
            (run_id, schedule_id, run_started_at, run_completed_at, status,
             agent_plan_json, report_volume_path, email_sent_to, email_sent_at)
        VALUES (%s, %s, now(), now(), %s, %s, %s, %s, %s)
        """,
        (
            run_id,
            schedule_id,
            "success",
            json.dumps({"findings": len(findings), "watching": len(memory_update.get("watching", []))}),
            volume_path,
            recipients if email_sent else None,
            datetime.utcnow() if email_sent else None,
        ),
    )

    return {
        "status": "success",
        "findings": findings,
        "report_md": report["report_md"],
        "html": report["html"],
        "pdf_bytes": report.get("pdf_bytes"),
        "email_sent": email_sent,
        "volume_path": volume_path,
        "run_id": run_id,
        "execution_time": memory_update.get("execution_time", 0),
    }


def run_preview(question: str, user_email: str, workspace_client=None) -> dict:
    """Run the Supervisor Agent and generate HTML + PDF without saving a schedule.

    Returns dict with: report, html, pdf_bytes, plan, execution_time.
    """
    from supervisor import SupervisorAgent

    agent = SupervisorAgent(workspace_client=workspace_client)
    result = agent.run(question=question, user_email=user_email)
    report_md = result.get("report", "")

    html_report = markdown_to_html(report_md, title="Report Preview")
    pdf_bytes = html_to_pdf(html_report, report_md=report_md, title="Report Preview")

    return {
        "report": report_md,
        "html": html_report,
        "pdf_bytes": pdf_bytes,
        "plan": result.get("plan", []),
        "genie_calls": result.get("genie_calls", 0),
        "execution_time": result.get("execution_time", 0),
    }


